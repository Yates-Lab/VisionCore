#!/usr/bin/env python3
"""Build a multi-unit audit gallery for corrected trajectory-phase engagement.

Each row deliberately separates three quantities: the measured periodic
SFxTF response surface, retinal power generated by the complete eye-position
trajectory for one objectively selected image, and the exact same-image model
rate change.  Continuous fitted peaks are annotations only; all engagement
scores use interpolated raw periodic responses.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import sys

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LogNorm
import numpy as np
import pandas as pd
from scipy.stats import spearmanr


ROOT = Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from paper.fig4.spatiotemporal_tuning.analyze_image_specific_joint_engagement import (
    interpolate_tuning_to_fft_bins,
)
from paper.fig4.spatiotemporal_tuning.compute_native_rucci_overlap import (
    EPS,
    observed_tuning_tensor,
)


BASE = ROOT / "outputs/dekel240_paper/m77_epoch279"
DEFAULT_GROUPED = BASE / "periodic_tuning_respaced/frequency_tuning_grouped.csv"
DEFAULT_ROBUST = BASE / "periodic_tuning_respaced/robust/robust_tuning_summary.csv"
DEFAULT_AUDIT = BASE / "periodic_tuning_respaced/fit_audit/m77_tuning_fit_audit.csv"
DEFAULT_ENGAGEMENT = (
    BASE
    / "figure4_real_trace_pilot_corrected/image_specific_joint_engagement_phase_spectrum"
    / "image_specific_joint_engagement.npz"
)
DEFAULT_OUT = (
    BASE
    / "figure4_real_trace_pilot_corrected/image_specific_joint_engagement_phase_spectrum"
    / "unit_gallery"
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--grouped-csv", type=Path, default=DEFAULT_GROUPED)
    parser.add_argument("--robust-summary", type=Path, default=DEFAULT_ROBUST)
    parser.add_argument("--audit-csv", type=Path, default=DEFAULT_AUDIT)
    parser.add_argument("--engagement-npz", type=Path, default=DEFAULT_ENGAGEMENT)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--n-units", type=int, default=6)
    return parser.parse_args()


def configure() -> None:
    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 7.5,
            "axes.titlesize": 8.2,
            "axes.titleweight": "semibold",
            "axes.labelsize": 7.5,
            "xtick.labelsize": 6.8,
            "ytick.labelsize": 6.8,
            "axes.spines.top": False,
            "axes.spines.right": False,
            "pdf.fonttype": 42,
            "svg.fonttype": "none",
        }
    )


def select_units(audit: pd.DataFrame, n_units: int) -> np.ndarray:
    trusted = audit.loc[audit.audit_category.eq("trusted")].sort_values(
        ["rms_preferred_tf_hz", "unit_index"]
    )
    if len(trusted) < n_units:
        raise ValueError(f"Only {len(trusted)} trusted units; requested {n_units}")
    positions = np.linspace(0, len(trusted) - 1, n_units).round().astype(int)
    return trusted.iloc[positions].unit_index.to_numpy(int)


def normalized_surface(value: np.ndarray) -> np.ndarray:
    value = np.maximum(np.asarray(value, dtype=float), 0.0)
    return value / max(float(np.nanmax(value)), EPS)


def render(args: argparse.Namespace) -> tuple[Path, pd.DataFrame]:
    grouped = pd.read_csv(args.grouped_csv)
    units, sf, probe_tf, orientation, raw, _ = observed_tuning_tensor(grouped)
    robust = pd.read_csv(args.robust_summary).set_index("unit_index")
    audit = pd.read_csv(args.audit_csv).set_index("unit_index")
    selected = select_units(audit.reset_index(), args.n_units)

    with np.load(args.engagement_npz, allow_pickle=False) as archive:
        method = str(archive["spectrum_method_version"].item())
        if not method.startswith("trajectory_phase"):
            raise RuntimeError(f"Invalid retinal spectrum method: {method}")
        archive_units = np.asarray(archive["unit_indices"], dtype=int)
        archive_sf = np.asarray(archive["spatial_cpd"], dtype=float)
        fft_tf = np.asarray(archive["temporal_hz"], dtype=float)
        archive_orientation = np.asarray(archive["orientation_deg"], dtype=float)
        image_power = np.asarray(archive["image_trajectory_phase_power"], dtype=float)
        joint = np.asarray(archive["joint_alignment_fraction"], dtype=float)
        total_dynamic_power = np.asarray(archive["total_dynamic_power"], dtype=float)
        moving = np.asarray(archive["moving_rate"], dtype=float)
        stable = np.asarray(archive["stabilized_rate"], dtype=float)
    if not np.array_equal(units, archive_units):
        raise ValueError("Tuning and engagement unit coordinates differ")
    np.testing.assert_allclose(sf, archive_sf)
    np.testing.assert_allclose(orientation, archive_orientation)
    interpolated = interpolate_tuning_to_fft_bins(raw, probe_tf, fft_tf)

    fig, axes = plt.subplots(
        len(selected),
        3,
        figsize=(11.6, 2.45 * len(selected)),
        gridspec_kw={"width_ratios": [1.0, 1.0, 0.92]},
        constrained_layout=True,
    )
    if len(selected) == 1:
        axes = axes[None]
    rows: list[dict[str, float | int | str]] = []
    for row_index, unit in enumerate(selected):
        unit_row = int(np.flatnonzero(units == unit)[0])
        global_fit = robust.loc[unit]
        unit_audit = audit.loc[unit]
        ori_index = int(
            np.argmin(np.abs(orientation - float(unit_audit.rms_best_orientation_deg)))
        )
        tuning = normalized_surface(interpolated[unit_row, :, :, ori_index]).T
        raw_tuning = normalized_surface(raw[unit_row, :, :, ori_index]).T
        best_image = int(np.argmax(joint[:, unit_row]))
        retinal = normalized_surface(image_power[best_image, :, :, ori_index]).T
        in_support = fft_tf <= float(probe_tf[-1])
        retinal_total = float(retinal[in_support].sum())
        halfmax_fraction = float(
            retinal[in_support][tuning[in_support] >= 0.5].sum()
            / max(retinal_total, EPS)
        )
        rate_delta = moving[:, unit_row] - stable[:, unit_row]
        correlation = spearmanr(joint[:, unit_row], rate_delta)
        total_power_correlation = spearmanr(total_dynamic_power, rate_delta)

        ax = axes[row_index, 0]
        tuning_plot = np.ma.masked_where(raw_tuning <= 0, raw_tuning)
        ax.contourf(
            sf,
            probe_tf,
            tuning_plot,
            levels=np.linspace(0, 1, 11),
            cmap="viridis",
            vmin=0,
            vmax=1,
        )
        sampled_sf, sampled_tf = np.meshgrid(sf, probe_tf)
        ax.scatter(
            sampled_sf,
            sampled_tf,
            s=6,
            facecolors="none",
            edgecolors="white",
            linewidths=0.35,
            alpha=0.8,
        )
        ax.scatter(
            float(unit_audit.rms_preferred_sf_cpd),
            float(unit_audit.rms_preferred_tf_hz),
            marker="*",
            s=55,
            color="#D55E00",
            edgecolor="white",
            linewidth=0.5,
            zorder=4,
            label="local joint peak",
        )
        ax.scatter(
            float(global_fit.preferred_sf_cpd),
            float(global_fit.preferred_tf_hz),
            marker="x",
            s=25,
            color="white",
            linewidth=0.8,
            zorder=4,
            label="old global center",
        )
        ax.set_title(
            f"u{unit:03d}: raw tuning at {orientation[ori_index]:g}°  "
            f"(local {float(unit_audit.rms_preferred_sf_cpd):.2f} c/deg, "
            f"{float(unit_audit.rms_preferred_tf_hz):.1f} Hz)",
            loc="left",
        )
        if row_index == 0:
            ax.legend(frameon=False, fontsize=5.8, loc="upper right")

        ax = axes[row_index, 1]
        positive = retinal[retinal > 0]
        floor = max(float(np.quantile(positive, 0.02)), float(positive.max()) * 1e-5)
        ax.contourf(
            sf,
            fft_tf,
            np.maximum(retinal, floor),
            levels=np.geomspace(floor, 1.0, 11),
            norm=LogNorm(vmin=floor, vmax=1.0),
            cmap="magma",
        )
        ax.contour(sf, fft_tf, tuning, levels=[0.5], colors="white", linewidths=1.0)
        ax.axhspan(1.0, fft_tf.min(), color="#B8B8B8", alpha=0.55, zorder=5)
        ax.text(
            sf.min() * 1.04,
            1.35,
            "unresolved by 333-ms trajectory",
            fontsize=5.5,
            color="#333333",
            zorder=6,
        )
        ax.set_title(
            f"image {best_image}: trajectory-phase power  "
            f"({100 * halfmax_fraction:.1f}% in half-max tuning)",
            loc="left",
        )

        ax = axes[row_index, 2]
        ax.axhline(0, color="#888888", lw=0.7)
        ax.scatter(joint[:, unit_row], rate_delta, s=20, color="#0072B2", alpha=0.78)
        for image_index, (x, y) in enumerate(zip(joint[:, unit_row], rate_delta)):
            ax.annotate(str(image_index), (x, y), xytext=(2, 2), textcoords="offset points", fontsize=5.5)
        ax.set_title(
            f"rate test: alignment $r_s$={float(correlation.statistic):.2f}; "
            f"total power $r_s$={float(total_power_correlation.statistic):.2f}",
            loc="left",
        )
        ax.set_xlabel("fraction of dynamic power aligned to joint tuning")
        ax.set_ylabel("moving − stabilized mean rate")

        for surface_ax in axes[row_index, :2]:
            surface_ax.set_xscale("log", base=2)
            surface_ax.set_yscale("log", base=2)
            surface_ax.set_xlim(sf.min(), sf.max())
            surface_ax.set_ylim(1.0, fft_tf.max())
            surface_ax.set_xticks([1, 2, 4, 8, 16], ["1", "2", "4", "8", "16"])
            surface_ax.set_yticks([1, 2, 3, 6, 12, 24, 48, 96], ["1", "2", "3", "6", "12", "24", "48", "96"])
            surface_ax.set_xlabel("spatial frequency (cycles/deg)")
            surface_ax.set_ylabel("temporal frequency (Hz)")

        rows.append(
            {
                "unit_index": int(unit),
                "best_orientation_deg": float(orientation[ori_index]),
                "interpolated_peak_sf_cpd": float(unit_audit.rms_preferred_sf_cpd),
                "interpolated_peak_tf_hz": float(unit_audit.rms_preferred_tf_hz),
                "old_global_center_tf_hz": float(unit_audit.rms_global_center_tf_hz),
                "rms_local_peak_r2": float(unit_audit.rms_local_peak_r2),
                "best_engagement_image": best_image,
                "trajectory_power_inside_tuning_halfmax_fraction": halfmax_fraction,
                "same_image_engagement_rate_delta_spearman": float(correlation.statistic),
                "same_image_engagement_rate_delta_p": float(correlation.pvalue),
                "same_image_total_dynamic_power_rate_delta_spearman": float(
                    total_power_correlation.statistic
                ),
                "spectrum_method_version": method,
            }
        )

    fig.suptitle(
        "M77 multi-unit audit: measured tuning, complete trajectory-phase retinal power, and causal rate change",
        fontsize=13,
        weight="bold",
    )
    fig.text(
        0.5,
        -0.006,
        "Heat maps are normalized within panel; white contour is the unit's half-max measured tuning. "
        "Stars are validated local joint peaks; gray crosses are the old global centers. "
        "Neither annotation enters the alignment score.",
        ha="center",
        va="top",
        fontsize=7,
        color="#555555",
    )
    args.out_dir.mkdir(parents=True, exist_ok=True)
    output = args.out_dir / "m77_trajectory_phase_unit_gallery.png"
    for suffix in ("png", "pdf"):
        fig.savefig(
            args.out_dir / f"m77_trajectory_phase_unit_gallery.{suffix}",
            dpi=250 if suffix == "png" else None,
            bbox_inches="tight",
            facecolor="white",
        )
    plt.close(fig)
    table = pd.DataFrame(rows)
    table.to_csv(args.out_dir / "m77_trajectory_phase_unit_gallery.csv", index=False)
    summary = {
        "analysis": "multi-unit corrected trajectory-phase audit",
        "selection": "evenly spaced ranks of interpolated TF among audit_category=trusted units",
        "selected_units": selected.tolist(),
        "n_images": int(joint.shape[0]),
        "spectrum_method_version": method,
        "claim_boundary": "The star is a local joint quadratic annotation only; the old global center is retained solely as a bias diagnostic. Retinal matching uses interpolated raw periodic responses. The displayed image maximizes each unit's joint engagement, while the right panel displays every image and therefore exposes whether engagement predicts the causal rate change.",
    }
    (args.out_dir / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    return output, table


def main() -> int:
    args = parse_args()
    configure()
    output, table = render(args)
    print(output)
    print(table.to_string(index=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
